"""TDD for ``scripts/gen_service_docs.py`` (Task 3).

``scripts/`` is added to ``sys.path`` by ``tests/tools/conftest.py``.
"""

import gen_service_docs as G

DOC_NAMES = {"ARCHITECTURE.md", "API.md", "DATABASE.md", "TESTING.md", "SPEC.md", "DESIGN.md"}


def test_all_services_yield_six_docs():
    m = G.load_manifest(G.ROOT)
    for name in m["service"]:
        docs = G.render_service_docs(G.ROOT, m, name)
        assert set(docs) == DOC_NAMES
        for text in docs.values():
            assert text.splitlines()[0].startswith("<!-- GENERATED by scripts/gen_service_docs.py")


def test_ledger_port_and_routers_from_ast():
    docs = G.render_service_docs(G.ROOT, G.load_manifest(G.ROOT), "ledger")
    assert "8451" in docs["ARCHITECTURE.md"]
    assert "nl_finance" in docs["API.md"]


def test_platform_inline_endpoint_listed():
    docs = G.render_service_docs(G.ROOT, G.load_manifest(G.ROOT), "platform")
    assert "/api/config" in docs["API.md"]


def test_gateway_has_port_without_routers():
    docs = G.render_service_docs(G.ROOT, G.load_manifest(G.ROOT), "gateway")
    assert "8444" in docs["ARCHITECTURE.md"]
    assert "/ws/" in docs["API.md"]


def test_api_table_records_auth_evidence():
    docs = G.render_service_docs(G.ROOT, G.load_manifest(G.ROOT), "ledger")
    assert "require_scope" in docs["API.md"]


def test_missing_service_raises():
    import pytest

    with pytest.raises(KeyError):
        G.render_service_docs(G.ROOT, {"service": {}}, "ledger")


def test_render_is_deterministic_with_explicit_stamp():
    m = G.load_manifest(G.ROOT)
    stamp = "2026-01-01T00:00:00Z"
    first = G.render_service_docs(G.ROOT, m, "market", stamp=stamp)
    second = G.render_service_docs(G.ROOT, m, "market", stamp=stamp)
    assert first == second
