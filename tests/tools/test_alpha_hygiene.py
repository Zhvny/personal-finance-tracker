def test_quarantine_apply_moves_and_records(tmp_path):
    (tmp_path / "docs" / "canon").mkdir(parents=True)
    (tmp_path / "docs" / "canon" / "a.md").write_text("A", encoding="utf-8")
    (tmp_path / "docs" / "dupe").mkdir()
    (tmp_path / "docs" / "dupe" / "a.md").write_text("A", encoding="utf-8")
    m = {"duplicates": {"docs/canon": {"canonical": "docs/canon", "paths": ["docs/dupe"]}}}
    done = H.quarantine(tmp_path, m, apply=True)
    assert len(done) == 1
    assert not (tmp_path / "docs" / "dupe").exists()  # moved, never deleted
    assert (tmp_path / "docs" / "_archive" / "dupe" / "a.md").read_text(encoding="utf-8") == "A"
    assert "docs/dupe" in (tmp_path / "docs" / "_archive" / "QUARANTINE_MANIFEST.md").read_text(encoding="utf-8")
