def _planned_srcs(root):
    plan = H.plan_quarantine(root, H.load_manifest(root))
    return {str(s.relative_to(root)).replace("\\", "/") for s, _, _ in plan}


def test_quarantine_plan_moves_only_identical_groups():
    srcs = _planned_srcs(ROOT)
    # identical / whole groups move while present; absent after --apply (idempotent)
    assert ("docs/planning/superpowers" in srcs) == (ROOT / "docs/planning/superpowers").exists()
    assert ("docs/perlu di perbaiki" in srcs) == (ROOT / "docs/perlu di perbaiki").exists()
    # unique-content dirs are in no quarantine group -> never moved
    assert not any(s.startswith("docs/planning/maestro") for s in srcs)
    assert not any(s.startswith("docs/archive/maestro") for s in srcs)
    assert not any(s.startswith("docs/AUDIT_2026-08-16") for s in srcs)
    # root junk
    assert any(s.endswith("wallet_search.txt") for s in srcs) == (ROOT / "wallet_search.txt").exists()


def test_quarantine_dry_run_touches_nothing():
    before = sorted(p.name for p in ROOT.iterdir())
    H.quarantine(ROOT, H.load_manifest(ROOT), apply=False)
    assert sorted(p.name for p in ROOT.iterdir()) == before


def test_plan_moves_only_whole_path_identical(tmp_path):
    (tmp_path / "docs" / "canon").mkdir(parents=True)
    (tmp_path / "docs" / "canon" / "a.md").write_text("A", encoding="utf-8")
    (tmp_path / "docs" / "dupe").mkdir()
    (tmp_path / "docs" / "dupe" / "a.md").write_text("A", encoding="utf-8")
    (tmp_path / "docs" / "uniq").mkdir()
    (tmp_path / "docs" / "uniq" / "b.md").write_text("B", encoding="utf-8")
    m = {"duplicates": {"docs/canon": {"canonical": "docs/canon", "paths": ["docs/dupe", "docs/uniq"]}}}
    srcs = {s.relative_to(tmp_path).as_posix() for s, _, _ in H.plan_quarantine(tmp_path, m)}
    assert srcs == {"docs/dupe"}  # uniq has unique content -> not moved
    assert H.review_manual(tmp_path, m) == [("docs/uniq", "docs/canon")]


def test_review_manual_excludes_whole_move_groups(tmp_path):
    (tmp_path / "docs" / "canon").mkdir(parents=True)
    (tmp_path / "docs" / "canon" / "a.md").write_text("A", encoding="utf-8")
    (tmp_path / "docs" / "whole").mkdir()
    (tmp_path / "docs" / "whole" / "b.md").write_text("B", encoding="utf-8")
    m = {
        "duplicates": {
            "docs/canon": {"canonical": "docs/canon", "paths": ["docs/whole"], "require_identical": False},
        }
    }
    # whole-move group is a move candidate, never a review-manual item
    assert H.review_manual(tmp_path, m) == []


