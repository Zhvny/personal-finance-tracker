def test_status_marks_quarantined_groups_as_done(tmp_path):
    """Duplicate group whose source is gone renders as done, not as a candidate."""
    (tmp_path / "docs" / "canon").mkdir(parents=True)
    (tmp_path / "docs" / "canon" / "a.md").write_text("A", encoding="utf-8")
    m = {
        "duplicates": {
            "docs/canon": {"canonical": "docs/canon", "paths": ["docs/canon"]},
            "docs/gone": {"canonical": "docs/gone", "paths": ["docs/missing", "docs/also-missing"]},
        }
    }
    out = H.build_status(tmp_path, m)
    assert "docs/missing" not in out and "docs/also-missing" not in out
    assert "sudah dikarantina" in out
    assert "docs/_archive/QUARANTINE_MANIFEST.md" in out
    # an existing source still renders as a live candidate
    assert "docs/canon" in out


def test_status_real_quarantined_groups_not_candidates():
    """Task-2 groups are known duplicates. The merged tree re-added their sources,
    so they render as handled quarantine candidates (canonical mapping) — never as
    review-manual items awaiting a human decision."""
    out = H.build_status(ROOT, H.load_manifest(ROOT))
    review = out.split("## Review manual", 1)[1].split("##", 1)[0]
    for group in (
        "docs/planning/superpowers",
        "docs/AUDIT-quality-perf-2026-08-23.md",
        "docs/perlu di perbaiki",
    ):
        assert group not in review, f"{group} must not await manual review"
        assert group in out, f"{group} must render as a handled duplicate"


