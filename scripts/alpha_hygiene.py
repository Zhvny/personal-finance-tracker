#!/usr/bin/env python3
"""Inventory + hygiene generator for the Alpha monorepo.

Derives ``docs/PROJECT_MAP.md`` and ``docs/STATUS.md`` from the repo so the docs
cannot go stale; only *judgement* lives in ``docs/project.toml``. Stdlib only.

Subcommands:
    map [--check]        regenerate the inventory docs (--check = exit 1 if stale)
    quarantine [--apply] move duplicate/junk paths into quarantine (dry-run by default)

honey: single-file generator; split into a package only when a second consumer
needs a stable API surface (Task 3 imports ``_services``/``load_manifest`` directly).
"""

from __future__ import annotations

import argparse
import ast
import hashlib
import re
import subprocess
import tomllib
from datetime import datetime, timezone
from pathlib import Path

HEADER = "<!-- GENERATED by scripts/alpha_hygiene.py \u2014 DO NOT EDIT BY HAND -->"
_STAMP_RE = re.compile(r"> Generated (\S+) ·")
_SKIP_DIRS = {"__pycache__", ".git", "node_modules", ".next", "dist", "build", ".pytest_cache", ".turbo"}


# --------------------------------------------------------------------------- paths / manifest


def _repo_root() -> Path:
    """Repo root from the script location (not cwd)."""
    return Path(__file__).resolve().parents[1]


def load_manifest(root: Path) -> dict:
    return tomllib.loads((root / "docs" / "project.toml").read_text(encoding="utf-8"))


def _generated_paths(root: Path, manifest: dict) -> set[Path]:
    return {(root / rel).resolve() for rel in manifest.get("meta", {}).get("generated_docs", [])}


def _stamp() -> str:
    return datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")


# --------------------------------------------------------------------------- service inventory


def _services(root: Path) -> dict:
    """Parse ``services/*/main.py`` with AST -> ``{name: {service_name, port, routers, inline}}``.

    Handles both port patterns verified in the repo:
    module-level ``DEFAULT_PORT = <int>`` (platform/portfolio/market) and an inline
    ``create_service_app(default_port=<int>)`` (ledger/insights/engagement). ``gateway``
    reads its port from ``os.getenv("ALPHA_GATEWAY_PORT", "8444")``.
    """
    out: dict[str, dict] = {}
    for main in sorted((root / "services").glob("*/main.py")):
        name = main.parent.name
        if name.startswith("_"):
            continue
        port: int | None = None
        service_name: str | None = None
        routers: list[str] = []
        inline: list[str] = []
        try:
            tree = ast.parse(main.read_text(encoding="utf-8"))
        except (OSError, SyntaxError):
            continue
        for node in ast.walk(tree):
            if isinstance(node, ast.Assign):
                for target in node.targets:
                    if not isinstance(target, ast.Name):
                        continue
                    if (
                        target.id == "DEFAULT_PORT"
                        and isinstance(node.value, ast.Constant)
                        and isinstance(node.value.value, int)
                    ):
                        port = node.value.value
                    if target.id == "ROUTERS" and isinstance(node.value, ast.List):
                        routers = [
                            e.value for e in node.value.elts if isinstance(e, ast.Constant) and isinstance(e.value, str)
                        ]
            if isinstance(node, ast.Call):
                func = node.func
                fname = (
                    func.attr if isinstance(func, ast.Attribute) else (func.id if isinstance(func, ast.Name) else None)
                )
                for kw in node.keywords:
                    if (
                        kw.arg == "default_port"
                        and isinstance(kw.value, ast.Constant)
                        and isinstance(kw.value.value, int)
                    ):
                        port = kw.value.value
                    if (
                        kw.arg == "service_name"
                        and isinstance(kw.value, ast.Constant)
                        and isinstance(kw.value.value, str)
                    ):
                        service_name = kw.value.value
                # gateway: os.getenv("ALPHA_GATEWAY_PORT", "8444")
                if (
                    fname == "getenv"
                    and node.args
                    and isinstance(node.args[0], ast.Constant)
                    and isinstance(node.args[0].value, str)
                ):
                    key = node.args[0].value
                    if "PORT" in key.upper() and len(node.args) > 1 and isinstance(node.args[1], ast.Constant):
                        raw = str(node.args[1].value)
                        if raw.isdigit():
                            port = int(raw)
            if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)):
                for dec in node.decorator_list:
                    if not isinstance(dec, ast.Call) or not isinstance(dec.func, ast.Attribute):
                        continue
                    if dec.func.attr not in ("get", "post", "put", "patch", "delete"):
                        continue
                    if dec.args and isinstance(dec.args[0], ast.Constant) and isinstance(dec.args[0].value, str):
                        path = dec.args[0].value
                        if path.startswith("/api/") and path not in inline:
                            inline.append(path)
        out[name] = {
            "service_name": service_name or f"alpha-{name}",
            "port": port,
            "routers": routers,
            "inline": inline,
        }
    return out


# --------------------------------------------------------------------------- filesystem / git helpers


def _count_files(directory: Path, exclude: set[Path]) -> int:
    total = 0
    for path in directory.rglob("*"):
        if not path.is_file():
            continue
        if any(part in _SKIP_DIRS for part in path.parts):
            continue
        if path.resolve() in exclude:
            continue
        total += 1
    return total


def _md5(path: Path) -> str:
    h = hashlib.md5()
    with path.open("rb") as fh:
        for chunk in iter(lambda: fh.read(65536), b""):
            h.update(chunk)
    return h.hexdigest()


def _dup_groups(root: Path, exclude: set[Path]) -> list[tuple[str, list[str]]]:
    """MD5 groups (hash appears >1x) across ``docs/``, excluding generated docs."""
    seen: dict[str, list[str]] = {}
    docs = root / "docs"
    if not docs.is_dir():
        return []
    for path in sorted(docs.rglob("*")):
        if not path.is_file() or path.resolve() in exclude:
            continue
        if any(part in _SKIP_DIRS for part in path.parts):
            continue
        seen.setdefault(_md5(path), []).append(path.relative_to(root).as_posix())
    groups = [(h, paths) for h, paths in seen.items() if len(paths) > 1]
    groups.sort(key=lambda g: (-len(g[1]), g[0]))
    return groups


def _git(root: Path, *args: str) -> str:
    try:
        proc = subprocess.run(
            ["git", *args], cwd=root, capture_output=True, text=True, encoding="utf-8", errors="replace", check=False
        )
    except OSError:
        return ""
    return proc.stdout if proc.returncode == 0 else ""


def _untracked_root(root: Path) -> list[str]:
    out = _git(root, "ls-files", "--others", "--exclude-standard")
    return sorted(line for line in out.splitlines() if line and "/" not in line)


def _debt_markers(root: Path, manifest: dict) -> list[str]:
    """``git grep`` for honey:/ponytail: markers in *code* only.

    Docs are excluded: the generated per-service docs (``services/<name>/docs/``)
    and generated inventory docs *quote* the literal ``honey:`` strings they
    report, so without the exclude each run would grep its own output and grow.
    Hand-authored root ``*.md`` are excluded for the same reason (spec 5: markers = code debt).
    """
    exclude = [f":(exclude){rel}" for rel in manifest.get("meta", {}).get("generated_docs", [])]
    out = _git(root, "grep", "-n", "-e", "honey:", "-e", "ponytail:", "--", ".", ":(exclude)*.md", *exclude)
    return [line for line in out.splitlines() if line.strip()]


# --------------------------------------------------------------------------- doc builders


def build_map(root: Path, manifest: dict, stamp: str | None = None) -> str:
    stamp = stamp or _stamp()
    services = _services(root)
    generated = _generated_paths(root, manifest)
    lines = [
        HEADER,
        "# Alpha — Project Map",
        "",
        f"> Generated {stamp} · regenerate: `python scripts/alpha_hygiene.py map`",
        ">",
        "> Inventaris generated: di mana apa, kanonik vs legacy, kandidat karantina.",
        "> Judgement (role/status/duplikat) berasal dari `docs/project.toml`.",
        "",
        "## Services",
        "",
        "| Service | Port | Routers | Inline endpoints |",
        "|---|---|---|---|",
    ]
    for _, info in sorted(services.items(), key=lambda kv: kv[1]["port"] or 0):
        routers = ", ".join(info["routers"]) or "—"
        inline = ", ".join(info["inline"]) or "—"
        lines.append(f"| `{info['service_name']}` | {info['port'] if info['port'] else '?'} | {routers} | {inline} |")
    lines += ["", "## Areas", "", "| Area | Role | Status | Files |", "|---|---|---|---|"]
    for area, meta in manifest.get("areas", {}).items():
        directory = root / area
        count = _count_files(directory, generated) if directory.is_dir() else 0
        lines.append(f"| `{area}` | {meta.get('role', '')} | {meta.get('status', '')} | {count} |")
    lines += ["", "## Duplicate groups (docs/, md5)", ""]
    groups = _dup_groups(root, generated)
    if groups:
        lines += ["| md5 | copies | paths |", "|---|---|---|"]
        for digest, paths in groups:
            lines.append(f"| `{digest[:8]}` | {len(paths)} | " + "<br>".join(f"`{p}`" for p in paths) + " |")
    else:
        lines.append("_none_")
    return "\n".join(lines) + "\n"


def _reported_changes(root: Path, manifest: dict) -> list[str]:
    """``git status`` entries minus the generated docs themselves.

    Without this, rewriting the (now tracked) generated docs would show up as a
    change on the next run, so ``map --check`` could never stabilise.
    """
    rels = {rel.replace("\\", "/") for rel in manifest.get("meta", {}).get("generated_docs", [])}
    changed = []
    for line in _git(root, "status", "--porcelain").splitlines():
        if not line.strip():
            continue
        path = line[3:].strip()
        if " -> " in path:  # rename/copy: "R  old -> new"
            path = path.split(" -> ")[-1].strip().strip('"')
        if path.replace("\\", "/") in rels:
            continue
        changed.append(line)
    return changed


def build_status(root: Path, manifest: dict, stamp: str | None = None) -> str:
    stamp = stamp or _stamp()
    branch = _git(root, "rev-parse", "--abbrev-ref", "HEAD").strip() or "(unknown)"
    porcelain = _reported_changes(root, manifest)
    lines = [
        HEADER,
        "# Alpha — Status",
        "",
        f"> Generated {stamp} · regenerate: `python scripts/alpha_hygiene.py map`",
        "",
        "## Git state",
        "",
        f"- branch: `{branch}`",
        f"- changed entries: {len(porcelain)}",
        "",
    ]
    if porcelain:
        lines += ["```", *porcelain, "```", ""]
    lines += ["## Known broken (manifest [[broken]])", "", "| Item | Symptom | Owner |", "|---|---|---|"]
    for broken in manifest.get("broken", []):
        lines.append(f"| {broken.get('item', '')} | {broken.get('symptom', '')} | {broken.get('owner', '')} |")
    lines += [
        "",
        "## Technical debt",
        "",
        "SSOT: [`docs/maintenance/HONEY_DEBT.md`](maintenance/HONEY_DEBT.md).",
        "",
        "Inline markers (`honey:` / `ponytail:`):",
        "",
    ]
    markers = _debt_markers(root, manifest)
    lines += [f"- `{m}`" for m in markers] or ["- _none_"]
    lines += ["", "## Quarantine candidates (manifest [duplicates])", ""]
    duplicates = manifest.get("duplicates", {})
    if duplicates:
        for group, spec in duplicates.items():
            rels = spec.get("paths", spec.get("quarantine", []))
            existing = [rel for rel in rels if (root / rel).exists()]
            canonical = spec.get("canonical", group)
            if rels and not existing:
                lines.append(
                    f"- kanonik `{canonical}`: semua sumber sudah dikarantina — "
                    "lihat `docs/_archive/QUARANTINE_MANIFEST.md`"
                )
            for candidate in existing:
                lines.append(f"- `{candidate}` → kanonik `{canonical}`")
    else:
        lines.append("_belum diisi (scan md5 di Task 2)._")
    review = manifest.get("review_manual", [])
    if review:
        lines += ["", "## Review manual (perlu keputusan manusia)", ""]
        for entry in review:
            lines.append(f"- `{entry.get('path', '')}` — {entry.get('reason', '')}")
    lines += ["", "## Root junk (untracked root + manifest [quarantine].root_junk)", ""]
    untracked = _untracked_root(root)
    present = [junk for junk in manifest.get("quarantine", {}).get("root_junk", []) if (root / junk).exists()]
    lines += [f"- git untracked: `{p}`" for p in untracked]
    lines += [f"- manifest junk present: `{p}`" for p in present]
    if not untracked and not present:
        lines.append("- _none_")
    return "\n".join(lines) + "\n"


def check_doc(path: Path, rendered: str) -> bool:
    try:
        return path.read_text(encoding="utf-8") == rendered
    except (FileNotFoundError, OSError):
        return False


# --------------------------------------------------------------------------- quarantine


def _hash_files(path: Path) -> dict[str, str]:
    """md5 per file under ``path`` (or of the file itself); ``{}`` when missing."""
    if path.is_file():
        return {path.name: _md5(path)}
    if not path.is_dir():
        return {}
    return {p.relative_to(path).as_posix(): _md5(p) for p in sorted(path.rglob("*")) if p.is_file()}


def _fully_duplicated(root: Path, rel: str, canonical_rel: str) -> bool:
    """True iff *every* file under ``rel`` has a byte-identical twin under the canonical path."""
    hashes = _hash_files(root / rel)
    if not hashes:
        return False
    canonical = set(_hash_files(root / canonical_rel).values())
    return all(digest in canonical for digest in hashes.values())


def _quarantine_mode(root: Path, rel: str) -> str:
    return "tracked" if _git(root, "ls-files", "--error-unmatch", "--", rel).strip() else "untracked"


def _quarantine_dest(root: Path, rel: str) -> Path:
    """``docs/_archive/<slug>`` — slug = basename with spaces -> dashes (dir or file)."""
    return root / "docs" / "_archive" / (root / rel).name.replace(" ", "-")


def plan_quarantine(root: Path, manifest: dict) -> list[tuple[Path, Path, str]]:
    """Planned ``(src, dest, mode)`` moves.

    ``require_identical`` groups move only when the whole path is byte-identical to
    ``canonical``; otherwise the path is left for ``review_manual`` (never moved).
    Root junk goes to ``_quarantine/root/``. Missing sources are skipped (idempotent).
    """
    moves: list[tuple[Path, Path, str]] = []
    for group, spec in manifest.get("duplicates", {}).items():
        canonical = spec.get("canonical", group)
        require_identical = bool(spec.get("require_identical", True))
        for rel in spec.get("paths", spec.get("quarantine", [])):
            if not (root / rel).exists():
                continue
            if require_identical and not _fully_duplicated(root, rel, canonical):
                continue
            moves.append((root / rel, _quarantine_dest(root, rel), _quarantine_mode(root, rel)))
    for name in manifest.get("quarantine", {}).get("root_junk", []):
        if not (root / name).exists():
            continue
        moves.append((root / name, root / "_quarantine" / "root" / name, _quarantine_mode(root, name)))
    return moves


def review_manual(root: Path, manifest: dict) -> list[tuple[str, str]]:
    """``(path, canonical)`` for divergent ``require_identical=true`` groups.

    Whole-move groups (``require_identical=false``) are excluded: they are move
    candidates, not review candidates. The stable, human-facing review list lives in
    the manifest ``[[review_manual]]`` array; this is the derived cross-check.
    """
    out: list[tuple[str, str]] = []
    for group, spec in manifest.get("duplicates", {}).items():
        if not bool(spec.get("require_identical", True)):
            continue
        canonical = spec.get("canonical", group)
        for rel in spec.get("paths", spec.get("quarantine", [])):
            if (root / rel).exists() and not _fully_duplicated(root, rel, canonical):
                out.append((rel, canonical))
    return out


def _git_mv(root: Path, src: Path, dest: Path) -> bool:
    proc = subprocess.run(
        ["git", "mv", src.relative_to(root).as_posix(), dest.relative_to(root).as_posix()],
        cwd=root,
        capture_output=True,
        text=True,
        encoding="utf-8",
        errors="replace",
        check=False,
    )
    return proc.returncode == 0


def _record_quarantine(root: Path, moves: list[tuple[Path, Path, str]]) -> None:
    """Append a dated src->dest table to ``docs/_archive/QUARANTINE_MANIFEST.md``."""
    if not moves:
        return
    path = root / "docs" / "_archive" / "QUARANTINE_MANIFEST.md"
    path.parent.mkdir(parents=True, exist_ok=True)
    rows = [
        f"| {mode} | `{src.relative_to(root).as_posix()}` | `{dest.relative_to(root).as_posix()}` |"
        for src, dest, mode in moves
    ]
    block = [f"## {_stamp()}", "", "| mode | src | dest |", "|---|---|---|", *rows, ""]
    if path.exists():
        with path.open("a", encoding="utf-8") as fh:
            fh.write("\n".join(block))
    else:
        header = [
            "# Quarantine manifest",
            "",
            "Reversible moves only — nothing is ever deleted. To revert, move each `dest` back to",
            "`src` (`git mv` when mode=tracked, a plain rename when untracked).",
            "",
        ]
        path.write_text("\n".join(header + block), encoding="utf-8")


def quarantine(root: Path, manifest: dict, apply: bool = False) -> list[tuple[Path, Path, str]]:
    """Return the plan; with ``apply=True`` perform the moves and record them. Never deletes."""
    moves = plan_quarantine(root, manifest)
    if not apply or not moves:
        return moves
    done: list[tuple[Path, Path, str]] = []
    for src, dest, mode in moves:
        if not src.exists():
            continue
        dest.parent.mkdir(parents=True, exist_ok=True)
        if mode != "tracked" or not _git_mv(root, src, dest):
            src.rename(dest)
        done.append((src, dest, mode))
    _record_quarantine(root, done)
    return done


# --------------------------------------------------------------------------- CLI


def _cmd_map(root: Path, manifest: dict, check: bool) -> int:
    """Write mode = all ``meta.generated_docs``; ``--check`` gates only ``meta.check_docs``.

    STATUS.md embeds a volatile git-state snapshot, so it is written but never
    gated — checking it would fail on any clean checkout (CI/another dev).
    """
    builders = {"PROJECT_MAP.md": build_map, "STATUS.md": build_status}
    meta = manifest.get("meta", {})
    generated = meta.get("generated_docs", [])
    targets = (meta.get("check_docs") or generated) if check else generated
    stale: list[str] = []
    for rel in targets:
        path = root / rel
        builder = builders[path.name]
        stamp = None
        if check and path.exists():
            match = _STAMP_RE.search(path.read_text(encoding="utf-8"))
            stamp = match.group(1) if match else None
        rendered = builder(root, manifest, stamp=stamp)
        if check:
            if not check_doc(path, rendered):
                stale.append(rel)
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(rendered, encoding="utf-8")
            print(f"wrote {rel}")
    if check:
        if stale:
            print("stale: " + ", ".join(stale))
            return 1
        print("docs up to date")
    return 0


def _cmd_quarantine(root: Path, manifest: dict, apply: bool) -> int:
    moves = quarantine(root, manifest, apply=True) if apply else plan_quarantine(root, manifest)
    for src, dest, mode in moves:
        print(f"{mode:9} {src.relative_to(root).as_posix()} -> {dest.relative_to(root).as_posix()}")
    verb = "applied" if apply else "planned (dry-run; pass --apply to execute)"
    print(f"{len(moves)} move(s) {verb}")
    return 0


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(prog="alpha_hygiene", description="Alpha repo inventory generator")
    sub = parser.add_subparsers(dest="cmd", required=True)
    map_parser = sub.add_parser("map", help="regenerate docs/PROJECT_MAP.md + docs/STATUS.md")
    map_parser.add_argument("--check", action="store_true", help="exit 1 if the generated docs are stale")
    q_parser = sub.add_parser("quarantine", help="move duplicate/junk paths into quarantine (reversible)")
    q_parser.add_argument("--apply", action="store_true", help="execute the moves (default: dry-run)")
    args = parser.parse_args(argv)

    root = _repo_root()
    manifest = load_manifest(root)
    if args.cmd == "map":
        return _cmd_map(root, manifest, args.check)
    if args.cmd == "quarantine":
        return _cmd_quarantine(root, manifest, args.apply)
    return 2


if __name__ == "__main__":
    raise SystemExit(main())
