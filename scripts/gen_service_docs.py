#!/usr/bin/env python3
"""Generate the per-service docs (6 each × 7 services) from code + manifest.

Everything derivable comes from the repo: the port/router inventory is reused
from :mod:`alpha_hygiene` (``_services``), endpoints/paths/auth from the AST of
``services/<name>/main.py`` and ``packages/api/backend/routers/<router>.py``,
tables from SQL string literals, tests from ``git grep``. Only *judgement*
(purpose / owns / known_gaps) comes from ``docs/project.toml``.

Nothing is invented: where a section has no evidence it renders an explicit
``_(...)`` placeholder instead of a guess. Stdlib only.

CLI:
    python scripts/gen_service_docs.py            write services/*/docs/*.md
    python scripts/gen_service_docs.py --check     exit 1 if any doc is stale
"""

from __future__ import annotations

import argparse
import ast
import re
from pathlib import Path

from alpha_hygiene import _STAMP_RE, _git, _repo_root, _services, _stamp, check_doc, load_manifest

ROOT = _repo_root()
HEADER = "<!-- GENERATED by scripts/gen_service_docs.py \u2014 DO NOT EDIT BY HAND -->"
REGEN = "`python scripts/gen_service_docs.py`"
DOC_NAMES = ("ARCHITECTURE.md", "API.md", "DATABASE.md", "TESTING.md", "SPEC.md", "DESIGN.md")

_HTTP_METHODS = {"get", "post", "put", "patch", "delete", "head", "options"}
# Uppercase SQL keywords only: lowercase "extracted from x.py" prose must not match.
_SQL_RE = re.compile(r"\b(?:FROM|INTO|UPDATE|JOIN)\s+([A-Za-z_][A-Za-z0-9_.]*)")
_SQL_STOP = {"SET", "INSTEAD", "THE", "THIS", "A", "AN", "AND", "OR", "IT", "THAT", "TABLE", "TABLES"}
_DB_HELPERS = ("DatabaseManager", "Database", "SqliteVirtualAccountRepository", "_query", "_execute", "_db")
_DEBT_MARKERS = ("honey:", "ponytail:")


# --------------------------------------------------------------------------- io helpers


def _read(path: Path) -> str:
    try:
        return path.read_text(encoding="utf-8")
    except OSError:
        return ""


def _service_main(root: Path, name: str) -> Path:
    return root / "services" / name / "main.py"


def _router_file(root: Path, router: str) -> Path | None:
    """Resolve a ``ROUTERS`` entry to its module: ``a.b.c`` -> ``a/b/c.py``."""
    if "." in router:
        path = root / f"{router.replace('.', '/')}.py"
    else:
        path = root / "packages" / "api" / "backend" / "routers" / f"{router}.py"
    return path if path.exists() else None


def _sources(root: Path, name: str, info: dict) -> list[Path]:
    """``services/<name>/main.py`` + every router module it mounts."""
    files = [p for p in [_service_main(root, name)] if p.exists()]
    for router in info.get("routers", []):
        path = _router_file(root, router)
        if path is not None:
            files.append(path)
    return files


# --------------------------------------------------------------------------- AST scans


def _dep_scope(node: ast.AST | None) -> str | None:
    """First ``require_scope("x")`` found under *node* -> ``"x"``."""
    if node is None:
        return None
    for sub in ast.walk(node):
        if isinstance(sub, ast.Call) and isinstance(sub.func, ast.Name) and sub.func.id == "require_scope":
            if sub.args and isinstance(sub.args[0], ast.Constant) and isinstance(sub.args[0].value, str):
                return sub.args[0].value
    return None


def _const_str(node: ast.AST | None) -> str | None:
    return node.value if isinstance(node, ast.Constant) and isinstance(node.value, str) else None


def scan_routes(text: str) -> list[dict]:
    """Endpoints declared in a module: ``[{'method','path','auth'}]`` (sorted).

    Handles ``APIRouter(prefix=...)`` + ``@router.get/post/...``, per-route and
    signature-level ``require_scope``, plus ``@app.api_route(methods=[...])`` and
    ``@app.websocket(...)`` used by the gateway.
    """
    try:
        tree = ast.parse(text)
    except SyntaxError:
        return []
    prefixes: dict[str, str] = {}
    router_scopes: dict[str, str | None] = {}
    for node in tree.body:
        if not (isinstance(node, ast.Assign) and isinstance(node.value, ast.Call)):
            continue
        func = node.value.func
        fname = func.attr if isinstance(func, ast.Attribute) else (func.id if isinstance(func, ast.Name) else None)
        if fname != "APIRouter":
            continue
        kw = {k.arg: k.value for k in node.value.keywords}
        for target in node.targets:
            if isinstance(target, ast.Name):
                prefixes[target.id] = _const_str(kw.get("prefix")) or ""
                router_scopes[target.id] = _dep_scope(kw.get("dependencies"))

    out: list[dict] = []
    for node in ast.walk(tree):
        if not isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)):
            continue
        sig_scope = _dep_scope(node.args)
        for dec in node.decorator_list:
            if not isinstance(dec, ast.Call) or not isinstance(dec.func, ast.Attribute):
                continue
            attr = dec.func.attr
            if attr == "api_route":
                methods: list[str] = []
                for kw in dec.keywords:
                    if kw.arg == "methods" and isinstance(kw.value, ast.List):
                        methods = [e.value for e in kw.value.elts if isinstance(e, ast.Constant)]
            elif attr == "websocket":
                methods = ["WS"]
            elif attr in _HTTP_METHODS:
                methods = [attr.upper()]
            else:
                continue
            path = _const_str(dec.args[0]) if dec.args else None
            if path is None:
                continue
            obj = dec.func.value.id if isinstance(dec.func.value, ast.Name) else None
            prefix = prefixes.get(obj, "") if obj else ""
            full = prefix.rstrip("/") + "/" + path.lstrip("/")
            auth = _dep_scope(dec) or (router_scopes.get(obj) if obj else None) or sig_scope
            for method in methods:
                out.append({"method": method, "path": full, "auth": auth, "object": obj})
    return sorted(out, key=lambda e: (e["path"], e["method"]))


def scan_env(text: str) -> dict[str, str | None]:
    """``os.getenv("NAME", default)`` -> ``{NAME: default}`` (None when no default)."""
    try:
        tree = ast.parse(text)
    except SyntaxError:
        return {}
    out: dict[str, str | None] = {}
    for node in ast.walk(tree):
        if isinstance(node, ast.Call) and isinstance(node.func, ast.Attribute) and node.func.attr == "getenv":
            name = _const_str(node.args[0]) if node.args else None
            if name is None:
                continue
            default = None
            if len(node.args) > 1 and isinstance(node.args[1], ast.Constant):
                default = repr(node.args[1].value)
            out[name] = default
    return out


def _string_constants(text: str) -> list[str]:
    try:
        tree = ast.parse(text)
    except SyntaxError:
        return []
    return [n.value for n in ast.walk(tree) if isinstance(n, ast.Constant) and isinstance(n.value, str)]


def scan_tables(text: str) -> list[str]:
    """Table names from uppercase SQL keywords inside string literals (heuristic)."""
    names: set[str] = set()
    for literal in _string_constants(text):
        for match in _SQL_RE.finditer(literal):
            token = match.group(1)
            if token.split(".")[-1].upper() not in _SQL_STOP:
                names.add(token)
    return sorted(names)


def scan_db_helpers(text: str) -> set[str]:
    """Names of DB accessors used without literal SQL (evidence of DB use)."""
    return {token for token in _DB_HELPERS if re.search(rf"\b{re.escape(token)}\b", text)}


def scan_db_paths(text: str) -> list[str]:
    """Literal names passed to ``Config.get_db_path("x")``."""
    try:
        tree = ast.parse(text)
    except SyntaxError:
        return []
    out = set()
    for node in ast.walk(tree):
        if isinstance(node, ast.Call) and isinstance(node.func, ast.Attribute) and node.func.attr == "get_db_path":
            name = _const_str(node.args[0]) if node.args else None
            if name:
                out.add(name)
    return sorted(out)


def scan_error_codes(text: str) -> list[int]:
    """Distinct 4xx/5xx ``status_code=<int>`` literals (evidence of error modes)."""
    codes = {int(m.group(1)) for m in re.finditer(r"status_code=(4\d\d|5\d\d)", text)}
    return sorted(codes)


def docstring(text: str) -> str:
    try:
        return ast.get_docstring(ast.parse(text)) or ""
    except SyntaxError:
        return ""


def _debt_lines(text: str) -> list[tuple[int, str]]:
    return [
        (i, line.strip())
        for i, line in enumerate(text.splitlines(), 1)
        if any(marker in line for marker in _DEBT_MARKERS)
    ]


# --------------------------------------------------------------------------- renderers


def _table(headers: list[str], rows: list[list[str]]) -> list[str]:
    lines = ["| " + " | ".join(headers) + " |", "|" + "---|" * len(headers)]
    lines += ["| " + " | ".join(row) + " |" for row in rows]
    return lines


def _bullet(items: list[str], empty: str = "_(none)_") -> list[str]:
    return [f"- {item}" for item in items] or [empty]


def _preamble(title: str, stamp: str) -> list[str]:
    return [HEADER, f"# {title}", "", f"> Generated {stamp} · regenerate: {REGEN}"]


def _router_rows(root: Path, info: dict) -> list[list[str]]:
    rows = []
    for router in info.get("routers", []):
        path = _router_file(root, router)
        text = _read(path) if path else ""
        endpoints = scan_routes(text)
        tags = ""
        for node in ast.parse(text).body if text else []:
            if isinstance(node, ast.Assign) and isinstance(node.value, ast.Call):
                for kw in node.value.keywords:
                    if kw.arg == "tags" and isinstance(kw.value, ast.List) and kw.value.elts:
                        tags = _const_str(kw.value.elts[0]) or ""
        source = path.relative_to(root).as_posix() if path else "_tidak ditemukan_"
        rows.append([f"`{router}`", f"`{source}`", tags or "—", str(len(endpoints))])
    return rows


def render_architecture(root: Path, spec: dict, name: str, info: dict, stamp: str) -> str:
    lines = _preamble(f"{info['service_name']} — Architecture", stamp)
    lines += ["", "## Purpose", "", spec.get("purpose", "_(not in manifest)_"), "", "## Runtime"]
    lines += _table(
        ["Property", "Value"],
        [
            ["Service name", f"`{info['service_name']}`"],
            ["Port", f"`{info['port']}`" if info.get("port") else "`?` _(not detected from AST)_"],
            ["Entry point", f"`services/{name}/main.py`"],
        ],
    )
    lines += ["", "## Owns (manifest)", ""] + _bullet([f"`{o}`" for o in spec.get("owns", [])])
    lines += ["", "## Routers", ""]
    rows = _router_rows(root, info)
    if rows:
        lines += _table(["Router", "Source", "Tags", "Endpoints"], rows)
    else:
        lines.append(
            f"_`{name}` declares no `ROUTERS`; its HTTP surface is built at runtime "
            "(see `API.md`) — gateway proxies downstream `/openapi.json`._"
        )
    lines += ["", "## Inline endpoints (from main.py, per alpha_hygiene._services)", ""]
    lines += _bullet([f"`{p}`" for p in info.get("inline", [])], empty="_(none)_")
    markers = [ln for ln in docstring(_read(_service_main(root, name))).splitlines() if _is_marker(ln)]
    lines += ["", "## Design notes in module docstring", ""]
    lines += _bullet(
        [f"`{m.strip()}`" for m in markers], empty="_(no honey:/ponytail: marker in the module docstring)_"
    )
    gaps = spec.get("known_gaps", [])
    if gaps:
        lines += ["", "## Known gaps (manifest)", ""] + _bullet(gaps)
    return "\n".join(lines) + "\n"


def _is_marker(line: str) -> bool:
    return any(marker in line for marker in _DEBT_MARKERS)


def render_api(root: Path, spec: dict, name: str, info: dict, stamp: str) -> str:
    lines = _preamble(f"{info['service_name']} — API", stamp)
    lines += [
        "",
        "Endpoints derived from the AST of the service's router modules and its inline "
        "`main.py` decorators. `Auth` is `require_scope(...)` only when the AST proves it.",
        "",
        "| Method | Path | Auth | Source |",
        "|---|---|---|---|",
    ]
    rows: list[list[str]] = []
    seen: set[tuple[str, str, str]] = set()
    for router in info.get("routers", []):
        path = _router_file(root, router)
        if path is None:
            continue
        source = f"`{path.relative_to(root).as_posix()}`"
        for e in scan_routes(_read(path)):
            _add_row(rows, seen, e, source)
    main_rel = f"`services/{name}/main.py`"
    for e in scan_routes(_read(_service_main(root, name))):
        _add_row(rows, seen, e, main_rel)
    if rows:
        lines += ["| " + " | ".join(r) + " |" for r in rows]
    else:
        lines.append("| — | _(no endpoints derived)_ | — | — |")
    if not info.get("routers"):
        lines += [
            "",
            "> Proxy service: the `/openapi.json` route table below is not hardcoded — it is "
            "assembled from every downstream at startup, so this file only lists gateway-local routes.",
        ]
    return "\n".join(lines) + "\n"


def _auth_cell(auth: str | None) -> str:
    return f'`require_scope("{auth}")`' if auth else "_(none detected)_"


def _add_row(rows: list[list[str]], seen: set[tuple[str, str, str]], entry: dict, source: str) -> None:
    """Append an API row, dropping duplicate ``(method, path, auth)`` (e.g. two handlers on one path)."""
    key = (entry["method"], entry["path"], entry["auth"] or "")
    if key in seen:
        return
    seen.add(key)
    rows.append([entry["method"], f"`{entry['path']}`", _auth_cell(entry["auth"]), source])


def _db_evidence(root: Path, name: str, info: dict) -> dict:
    tables: dict[str, set[str]] = {}
    search_path: list[str] = []
    db_paths: list[str] = []
    helpers: set[str] = set()
    for path in _sources(root, name, info):
        text = _read(path)
        rel = path.relative_to(root).as_posix()
        if "search_path" in text:
            search_path.append(rel)
        for table in scan_tables(text):
            tables.setdefault(table, set()).add(rel)
        paths = scan_db_paths(text)
        if paths:
            db_paths.append(f"{rel} -> `{', '.join(paths)}`")
        helpers |= scan_db_helpers(text)
    return {"tables": tables, "search_path": search_path, "db_paths": db_paths, "helpers": sorted(helpers)}


def render_database(root: Path, spec: dict, name: str, info: dict, stamp: str) -> str:
    lines = _preamble(f"{info['service_name']} — Database", stamp)
    ev = _db_evidence(root, name, info)
    if not (ev["tables"] or ev["search_path"] or ev["db_paths"] or ev["helpers"]):
        lines += ["", "_(tidak ada akses DB terdeteksi dari router)_"]
        return "\n".join(lines) + "\n"
    lines += ["", "## Tables referenced in SQL literals", ""]
    if ev["tables"]:
        rows = [[f"`{t}`", ", ".join(f"`{f}`" for f in sorted(files))] for t, files in sorted(ev["tables"].items())]
        lines += _table(["Table", "Referenced in"], rows)
        lines += ["", "_Extracted heuristically from uppercase SQL string literals — not a schema contract._"]
    else:
        lines.append("_(tidak ada nama tabel literal terdeteksi)_")
    lines += ["", "## Per-profile isolation (`search_path`)", ""]
    lines += _bullet(
        [f"`{f}`" for f in ev["search_path"]],
        empty="_(tidak ada referensi search_path terdeteksi di sumber service ini)_",
    )
    if ev["db_paths"]:
        lines += ["", "## Legacy SQLite paths (`Config.get_db_path`)", ""] + _bullet(ev["db_paths"])
    if ev["helpers"]:
        lines += ["", "## DB helpers used (literal SQL not in this file)", ""]
        lines += _bullet([f"`{h}`" for h in ev["helpers"]])
    return "\n".join(lines) + "\n"


def render_testing(root: Path, spec: dict, name: str, info: dict, stamp: str) -> str:
    lines = _preamble(f"{info['service_name']} — Testing", stamp)
    out = _git(root, "grep", "-l", "-e", name, "--", "tests")
    # Exclude tests/tools: they test the doc generators themselves (and would
    # otherwise self-reference every service named in their fixtures/assertions).
    files = sorted(line for line in out.splitlines() if line.strip() and not line.startswith("tests/tools/"))
    lines += [
        "",
        f"Test files matching `git grep -l {name} tests/` (substring match, `tests/tools/` excluded — "
        "those test the doc tooling). Some hits may be incidental.",
        "",
    ]
    if files:
        lines += _table(["Test file", "Run"], [[f"`{f}`", f"`python -m pytest {f} -q`"] for f in files])
    else:
        lines.append(f"_no test file under `tests/` mentions `{name}`_")
    lines += ["", "## Full gate", "", "```", "python -m pytest -q", "ruff check .", "```"]
    return "\n".join(lines) + "\n"


def render_spec(root: Path, spec: dict, name: str, info: dict, stamp: str) -> str:
    lines = _preamble(f"{info['service_name']} — Spec", stamp)
    text = _read(_service_main(root, name))
    lines += ["", "## Environment", ""]
    env = scan_env(text)
    rows = [["Port", f"`{info['port']}`" if info.get("port") else "`?`", f"`services/{name}/main.py`"]]
    rows += [
        [f"`{k}`", f"`{v}`" if v is not None else "_(no literal default)_", f"`services/{name}/main.py`"]
        for k, v in sorted(env.items())
    ]
    lines += _table(["Setting", "Default", "Source"], rows)
    scopes: dict[str, int] = {}
    for src in _sources(root, name, info):
        for e in scan_routes(_read(src)):
            if e["auth"]:
                scopes[e["auth"]] = scopes.get(e["auth"], 0) + 1
    lines += ["", "## Auth scopes", ""]
    if scopes:
        lines += _table(
            ["Scope", "Endpoints"], [[f'`require_scope("{s}")`', str(c)] for s, c in sorted(scopes.items())]
        )
        lines += ["", "Only `/health*` is public (repo rule: every `/api/*` route requires a scope)."]
    else:
        lines.append("_(tidak ada require_scope terdeteksi dari sumber service ini)_")
    codes: set[int] = set()
    for src in _sources(root, name, info):
        codes |= set(scan_error_codes(_read(src)))
    lines += ["", "## Error modes", ""]
    if codes:
        lines += _bullet([f"`{c}`" for c in sorted(codes)], empty="_(none)_")
        lines += ["", "_Distinct status codes literal in the AST (`status_code=<n>`)._"]
    else:
        lines.append("_(tidak ada status_code literal terdeteksi)_")
    gaps = spec.get("known_gaps", [])
    if gaps:
        lines += ["", "## Constraints (manifest known_gaps)", ""] + _bullet(gaps)
    return "\n".join(lines) + "\n"


def render_design(root: Path, spec: dict, name: str, info: dict, stamp: str) -> str:
    lines = _preamble(f"{info['service_name']} — Design", stamp)
    lines += [
        "",
        "## Module docstring (`services/%s/main.py`)" % name,
        "",
        "```python",
        docstring(_read(_service_main(root, name))).rstrip(),
        "```",
    ]
    markers: list[list[str]] = []
    for src in _sources(root, name, info):
        rel = src.relative_to(root).as_posix()
        for lineno, line in _debt_lines(_read(src)):
            markers.append([f"`{rel}:{lineno}`", line])
    lines += ["", "## Inline debt markers (`honey:` / `ponytail:`)", ""]
    if markers:
        lines += _table(["Location", "Marker"], markers)
    else:
        lines.append("_(none)_")
    gaps = spec.get("known_gaps", [])
    if gaps:
        lines += ["", "## Known gaps (manifest)", ""] + _bullet(gaps)
    return "\n".join(lines) + "\n"


# --------------------------------------------------------------------------- public API


def render_service_docs(root: Path, manifest: dict, name: str, stamp: str | None = None) -> dict[str, str]:
    """Render the 6 docs for *name* -> ``{filename: text}``.

    Raises ``KeyError`` when *name* has no ``[service.<name>]`` entry in the
    manifest (fail loud — a missing service must not silently drop 6 docs).
    """
    spec = manifest["service"][name]
    stamp = stamp or _stamp()
    info = _services(root).get(name) or {
        "service_name": f"alpha-{name}",
        "port": None,
        "routers": [],
        "inline": [],
    }
    builders = {
        "ARCHITECTURE.md": render_architecture,
        "API.md": render_api,
        "DATABASE.md": render_database,
        "TESTING.md": render_testing,
        "SPEC.md": render_spec,
        "DESIGN.md": render_design,
    }
    return {filename: builder(root, spec, name, info, stamp) for filename, builder in builders.items()}


def _docs_dir(root: Path, name: str) -> Path:
    return root / "services" / name / "docs"


def run(root: Path, manifest: dict, check: bool = False) -> int:
    stamp = None if check else _stamp()
    stale: list[str] = []
    written = 0
    for name in sorted(manifest.get("service", {})):
        if check:
            anchor = _docs_dir(root, name) / "ARCHITECTURE.md"
            match = _STAMP_RE.search(_read(anchor))
            docs = render_service_docs(root, manifest, name, stamp=match.group(1) if match else None)
            for filename, text in docs.items():
                path = _docs_dir(root, name) / filename
                if not check_doc(path, text):
                    stale.append(path.relative_to(root).as_posix())
        else:
            docs = render_service_docs(root, manifest, name, stamp=stamp)
            for filename, text in docs.items():
                path = _docs_dir(root, name) / filename
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_text(text, encoding="utf-8")
                written += 1
    if check:
        if stale:
            print("stale:\n  " + "\n  ".join(stale))
            return 1
        print("service docs up to date")
        return 0
    print(f"wrote {written} file(s) under services/*/docs/")
    return 0


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        prog="gen_service_docs", description="Generate per-service docs from code + manifest"
    )
    parser.add_argument("--check", action="store_true", help="exit 1 if any generated doc differs from disk")
    args = parser.parse_args(argv)
    return run(ROOT, load_manifest(ROOT), args.check)


if __name__ == "__main__":
    raise SystemExit(main())
